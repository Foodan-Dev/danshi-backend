CREATE TABLE image_access_deliveries (
    image_asset_id       bigint PRIMARY KEY REFERENCES image_assets(id) ON DELETE CASCADE,
    desired_intent_id    bigint NOT NULL UNIQUE,
    desired_public       boolean NOT NULL,
    purge_required       boolean NOT NULL DEFAULT true,
    generation           bigint NOT NULL DEFAULT 1 CHECK (generation > 0),
    state                text NOT NULL DEFAULT 'pending_acl'
                         CHECK (state IN (
                             'pending_acl', 'pending_submit', 'submitting',
                             'submitted', 'succeeded', 'dead_letter'
                         )),
    acl_attempts         integer NOT NULL DEFAULT 0 CHECK (acl_attempts >= 0),
    submit_attempts      integer NOT NULL DEFAULT 0 CHECK (submit_attempts >= 0),
    poll_attempts        integer NOT NULL DEFAULT 0 CHECK (poll_attempts >= 0),
    unknown_checks       integer NOT NULL DEFAULT 0 CHECK (unknown_checks >= 0),
    provider_job_id      text,
    submission_started_at timestamptz,
    next_attempt_at      timestamptz DEFAULT now(),
    lease_token          text,
    lease_until          timestamptz,
    last_error_code      text,
    completed_at         timestamptz,
    dead_lettered_at     timestamptz,
    created_at           timestamptz NOT NULL DEFAULT now(),
    updated_at           timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT fk_image_access_delivery_intent
        FOREIGN KEY (desired_intent_id, image_asset_id, desired_public)
        REFERENCES image_access_intents(id, image_asset_id, desired_public) ON DELETE CASCADE,
    CHECK ((lease_token IS NULL) = (lease_until IS NULL)),
    CHECK (lease_token IS NULL OR length(lease_token) BETWEEN 16 AND 64),
    CHECK (provider_job_id IS NULL OR length(provider_job_id) BETWEEN 1 AND 128),
    CHECK (last_error_code IS NULL OR last_error_code IN (
        'acl_retryable', 'acl_exhausted',
        'submit_retryable', 'submit_unknown', 'submit_permanent', 'submit_exhausted',
        'discover_retryable', 'discover_permanent', 'discover_exhausted',
        'poll_retryable', 'poll_permanent', 'provider_failed', 'provider_timeout',
        'provider_canceled', 'provider_pending_timeout', 'poll_exhausted'
    )),
    CHECK (state <> 'submitting' OR submission_started_at IS NOT NULL),
    CHECK (state <> 'submitted' OR (provider_job_id IS NOT NULL AND submission_started_at IS NOT NULL)),
    CHECK (state <> 'succeeded' OR completed_at IS NOT NULL),
    CHECK (state <> 'dead_letter' OR dead_lettered_at IS NOT NULL),
    CHECK (purge_required OR state IN ('pending_acl', 'succeeded', 'dead_letter')),
    CHECK ((state IN ('succeeded', 'dead_letter')) = (next_attempt_at IS NULL))
);

COMMENT ON TABLE image_access_deliveries IS
    '审核图片 ACL 与 EdgeOne 精确刷新事务 outbox；每个资产只保存最新期望状态，不保存 URL/对象键';

CREATE INDEX idx_image_access_deliveries_due
    ON image_access_deliveries (next_attempt_at, image_asset_id)
    WHERE state NOT IN ('succeeded', 'dead_letter');

CREATE INDEX idx_image_access_deliveries_lease
    ON image_access_deliveries (lease_until)
