-- +goose StatementBegin
CREATE OR REPLACE FUNCTION danshi_validate_image_access_intent()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = pg_catalog
AS $func$
DECLARE source_verdict text;
BEGIN
    SELECT verdict INTO source_verdict
      FROM public.moderation_records
     WHERE id = NEW.source_moderation_record_id
       AND image_asset_id = NEW.image_asset_id;
    IF NOT FOUND OR NEW.desired_public IS DISTINCT FROM (source_verdict = 'pass') THEN
        RAISE EXCEPTION 'image access intent does not match moderation verdict'
            USING ERRCODE = 'check_violation';
    END IF;
    RETURN NEW;
END;
$func$;
-- +goose StatementEnd

CREATE TRIGGER trg_image_access_intents_validate
    BEFORE INSERT ON image_access_intents
    FOR EACH ROW EXECUTE FUNCTION danshi_validate_image_access_intent();

