-- v11 已经可能存在通过、待复核或违规的完成态资产。升级时必须把它们的
-- 当前审核事实投影进 durable outbox，否则旧 review/block 只能等待一次未来
-- 回调才会收敛 ACL/CDN。所有历史图片审核行都先 grandfather 为 immutable
-- intent，使旧 provider callback 的重复投递仍命中 source 幂等键；每张完成态
-- 图片再选择与当前 image_assets.moderation 一致的最新 intent 作为 delivery。
-- 历史状态转换无法从当前快照可靠重建，因此所有 grandfather delivery 都保守地
-- 标记 purge_required=true：这可能多刷一次，但不会漏掉曾以公开响应或 403 被缓存的 URL。
-- 找不到事实时中止迁移，避免静默留下不可交付资产。
-- +goose StatementBegin
DO $block$
BEGIN
    IF EXISTS (
        SELECT 1
        FROM image_assets AS asset
        WHERE asset.moderation IN ('pass', 'review', 'block')
          AND asset.public_url <> ''
          AND asset.public_url NOT LIKE 'urn:danshi:image-asset:%:retired'
          AND NOT EXISTS (
              SELECT 1
              FROM moderation_records AS source
              WHERE source.image_asset_id = asset.id
                AND source.verdict = asset.moderation
          )
    ) THEN
        RAISE EXCEPTION
            'cannot grandfather image access outbox: terminal asset lacks matching moderation fact'
            USING ERRCODE = 'check_violation';
    END IF;
END;
$block$;
-- +goose StatementEnd

INSERT INTO image_access_intents
    (image_asset_id, source_moderation_record_id, desired_public, created_at)
SELECT image_asset_id, id, (verdict = 'pass'), now()
FROM moderation_records
WHERE image_asset_id IS NOT NULL
ORDER BY id;

INSERT INTO image_access_deliveries (
    image_asset_id, desired_intent_id, desired_public, purge_required, generation, state,
    next_attempt_at, created_at, updated_at
)
SELECT asset.id, desired.id, desired.desired_public, true, 1, 'pending_acl',
       now(), now(), now()
FROM image_assets AS asset
CROSS JOIN LATERAL (
    SELECT intent.id, intent.desired_public
    FROM image_access_intents AS intent
    JOIN moderation_records AS source
      ON source.id = intent.source_moderation_record_id
    WHERE intent.image_asset_id = asset.id
      AND source.verdict = asset.moderation
    ORDER BY source.created_at DESC, source.id DESC
    LIMIT 1
) AS desired
WHERE asset.moderation IN ('pass', 'review', 'block')
  AND asset.public_url <> ''
  AND asset.public_url NOT LIKE 'urn:danshi:image-asset:%:retired';


