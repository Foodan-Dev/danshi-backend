CREATE OR REPLACE FUNCTION danshi_forbid_image_access_intent_rewrite()
RETURNS trigger
LANGUAGE plpgsql
AS $func$
BEGIN
    IF TG_OP = 'DELETE'
       AND current_setting('danshi.allow_image_asset_delete', true) = 'on' THEN
        RETURN OLD;
    END IF;
    RAISE EXCEPTION 'image access intents are append-only'
        USING ERRCODE = 'object_not_in_prerequisite_state';
END;
$func$;
-- +goose StatementEnd

