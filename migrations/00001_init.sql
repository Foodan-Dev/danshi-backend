-- ============================================================
-- user_sessions：会话表，令牌撤销的唯一真源
--
-- 旧实现的 /auth/logout 是个空壳（源码注释自陈「jwt 无状态，无需禁用 token」），
-- 只有前端删掉本地存储，token 本身在服务端仍然有效直到过期——refresh 最长 30 天。
--
-- 新模型：**access token 与 refresh token 都绑定到一条会话行，两者都不是无状态的**。
-- 一行 = 一台设备的一次登录。
--
--   access  { sub, sid, iat, exp, type:"access"  }
--   refresh { sub, sid, iat, exp, type:"refresh" }
--
-- 每个需要鉴权的请求都按 sid 查本表：
--   命中且 revoked_at IS NULL 且未过期 → 放行；否则 401。
-- 因此撤销**一律立即生效**，没有「access token 还能再用一会儿」的窗口：
--   本设备登出   → 撤销该行
--   登出所有设备 → 撤销该用户全部行
--   踢掉某设备   → 撤销那一行
-- 不需要额外的版本号、黑名单或撤销时序表。
--
-- 成本：每请求多一次主键查找。鉴权本来就要查 users，实现上与 users 一次 JOIN 取回即可，
-- 不增加往返次数。
--
-- refresh token 在会话生命周期内不轮转：摘要固定，撤销才是安全机制。
-- 不做轮转就没有「弱网重试被误判为重放」的问题，也不需要宽限窗口。
-- 代价是 refresh token 若泄露，攻击者可在会话有效期内冒用——
-- 对应的处置手段是用户在「我的登录设备」里看到陌生设备并踢掉。
-- ============================================================

CREATE TABLE user_sessions (
    id                    bigint      PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    user_id               bigint      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    refresh_token_digest  char(64)    NOT NULL,
    device_label          varchar(100),
    user_agent            varchar(512),
    -- IP 用 varchar 而非 inet：只用于展示，不做网段运算，
    -- 且 inet 在 GORM/pgx 侧需要自定义类型，不值得为此增加摩擦。45 字符可容纳 IPv6。
    ip                    varchar(45),
    created_at            timestamptz NOT NULL DEFAULT now(),
    last_seen_at          timestamptz NOT NULL DEFAULT now(),
    expires_at            timestamptz NOT NULL,
    revoked_at            timestamptz,

    -- 摘要是 sha256 十六进制；char(64) 已限长，此约束排除大写与非法字符
    CONSTRAINT user_sessions_digest_format_check
        CHECK (refresh_token_digest ~ '^[0-9a-f]{64}$'),
    -- 时间顺序：过期必须晚于创建，活跃与撤销不能早于创建
    CONSTRAINT user_sessions_expires_after_created_check CHECK (expires_at   > created_at),
    CONSTRAINT user_sessions_seen_after_created_check    CHECK (last_seen_at >= created_at),
    CONSTRAINT user_sessions_revoked_after_created_check
        CHECK (revoked_at IS NULL OR revoked_at >= created_at),
    -- 会话过期或撤销之后不可能再有活跃记录
    CONSTRAINT user_sessions_seen_before_expires_check CHECK (last_seen_at <= expires_at),
    CONSTRAINT user_sessions_seen_before_revoked_check
        CHECK (revoked_at IS NULL OR last_seen_at <= revoked_at)
);

CREATE UNIQUE INDEX uq_user_sessions_digest ON user_sessions (refresh_token_digest);
-- 「我的登录设备」列表：只看仍然有效的会话
CREATE INDEX idx_user_sessions_active ON user_sessions (user_id, last_seen_at DESC)
    WHERE revoked_at IS NULL;
-- 过期会话清理任务
CREATE INDEX idx_user_sessions_expires ON user_sessions (expires_at)
    WHERE revoked_at IS NULL;

COMMENT ON TABLE user_sessions IS
  '一行 = 一台设备的一次登录，是令牌是否有效的唯一真源。'
  'refresh token 只存 sha256 摘要，明文不落库——数据库泄露不等于会话可被冒用。';
COMMENT ON COLUMN user_sessions.refresh_token_digest IS
  '该会话 refresh token 的 sha256 十六进制摘要。会话存续期间不变（不做轮转）。';
COMMENT ON COLUMN user_sessions.device_label IS
  '设备名，可由用户命名或从 User-Agent 解析。用于「我的登录设备」列表展示与识别陌生登录。';
COMMENT ON COLUMN user_sessions.last_seen_at IS
  '最后活跃时刻。⚠ 不要每个请求都写，否则每次鉴权都变成一次写事务；'
  '应用层应设节流阈值（如距上次超过 5 分钟才更新）。';
COMMENT ON COLUMN user_sessions.expires_at IS
  '会话绝对过期时间（登录时 + JWT_REFRESH_EXPIRE_DAYS）。到期必须重新登录。';
COMMENT ON COLUMN user_sessions.revoked_at IS
  '非空即失效，鉴权立刻拒绝。行不物理删除，保留供安全审计与「最近登出记录」展示。';


-- ============================================================
-- post_histories / comment_histories：编辑历史快照
--
-- 帖子与评论都可以编辑。当前内容始终只保存在主表，历史表只保存被替换的旧版本：
--   创建 → 不写历史，当前版本号为 1
--   首次编辑 → 旧内容写 revision 1，新内容留在主表且当前版本号为 2
-- 因此历史 revision N 就是第 N 版内容，当前版本号 = 最大历史 revision + 1。
-- 00015 用 moderation_records.content_revision 直接记录被审版本号，不把尚在主表里的
-- 当前内容重复写入历史表，也不要求审核流水外键指向当时尚不存在的历史行。
--
-- 用途：申诉与追责（「他改之前写的是什么」）、机审复核、以及编辑滥用排查
-- （发一条正常内容过审后再改成违规内容，是内容平台的经典绕过手法——
--  有了快照，机审可以对每个新版本重新跑，管理员也能看到改动轨迹）。
--
-- 帖子的可编辑字段跨了 posts、post_tags、post_flavors、post_images 四张表，
-- 用 jsonb 整体快照而不是逐列建镜像表：快照是只读的历史证据，不参与查询与外键，
-- 逐列建表既繁琐又会在 schema 演进时产生两套需要同步维护的定义。
-- ============================================================

CREATE TABLE post_histories (
    id          bigint      PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    post_id     bigint      NOT NULL REFERENCES posts (id) ON DELETE CASCADE,
    revision    integer     NOT NULL,
    edited_by   bigint      NOT NULL REFERENCES users (id) ON DELETE RESTRICT,
    edited_at   timestamptz NOT NULL DEFAULT now(),
    -- 该版本的完整内容快照
    snapshot    jsonb       NOT NULL,
    edit_reason varchar(200),

    CONSTRAINT post_histories_snapshot_object_check
        CHECK (jsonb_typeof(snapshot) = 'object'),
    CONSTRAINT post_histories_revision_check CHECK (revision >= 1),
    CONSTRAINT uq_post_histories_revision UNIQUE (post_id, revision),
    -- 供 moderation_records 的复合外键引用：审核记录必须指向**同一个帖子**的版本
    CONSTRAINT uq_post_histories_id_post UNIQUE (id, post_id)
);

CREATE INDEX idx_post_histories_post ON post_histories (post_id, edited_at DESC);
CREATE INDEX idx_post_histories_editor ON post_histories (edited_by, edited_at DESC);

-- 编辑历史是追加不可篡改的：改快照等于伪造证据，删快照等于销毁证据。
-- DELETE 复用 danshi_forbid_hard_delete，因此运维物理清除帖子时（开逃生阀）能正常级联。
CREATE TRIGGER trg_post_histories_immutable
    BEFORE UPDATE ON post_histories
    FOR EACH ROW EXECUTE FUNCTION danshi_forbid_row_update();
CREATE TRIGGER trg_post_histories_forbid_delete
    BEFORE DELETE ON post_histories
    FOR EACH ROW EXECUTE FUNCTION danshi_forbid_hard_delete();

COMMENT ON TABLE post_histories IS
  '帖子的**全量版本表**。创建写 revision 1，每次编辑追加一版并把主表同步为该版内容，'
  '因此「主表 == 最新一条历史」。追加不可篡改，不参与业务查询。';
COMMENT ON COLUMN post_histories.revision IS
  '版本号，从 1 起单调递增。moderation_records 用 (post_id, post_history_id) 复合外键'
  '锚定「这条审核结论审的是哪一版」。';
COMMENT ON COLUMN post_histories.snapshot IS
  '编辑前的完整内容，至少包含 title / content / category / share_type / price / '
  'budget_min / budget_max / canteen_id / canteen_window_id / cuisine_id / '
  'tags / flavors / images（后三者展开为名称或 id 数组）。'
  '用 jsonb 是因为可编辑字段跨四张表，且快照是历史证据而非查询对象。';
COMMENT ON COLUMN post_histories.edited_by IS
  '执行编辑的人。通常是作者，管理员代为修改时记管理员。外键用 RESTRICT，留痕不可丢。';

