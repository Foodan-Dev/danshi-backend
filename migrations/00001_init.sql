-- ============================================================
-- moderation_records：内容审核流水
--
-- 审核范围：**一切用户可输入的内容**——帖子标题与正文、评论正文、话题标签、
-- 用户昵称与个人简介、以及所有上传的图片。
--
-- 时序分两类：
--   帖子   **先审后发**：提交后停在 pending，机审通过才 approved；
--          机审判需复核则继续停在 pending 等人工裁决（放行或禁止）。
--   其余   **先发后审**：评论、标签、昵称、简介发出即可见，机审异步跟进，
--          判违规则软删除 / 下架，并通知管理员（如飞书机器人）。
--   封闭词表（口味 / 菜系 / 餐厅 / 窗口）不走机审，走 dictionary_suggestions 人工审核。
-- 审核策略（产品口径）：只允许美食与就餐相关内容；违法乱纪、涉政、色情、广告一律拦截。
-- 判定为违规时由管理员决定是否封禁作者（users.banned_until，支持限时）。
--
-- **provider 是可替换的**：后端定义统一的审核接口，腾讯云数据万象只是第一个实现。
-- 本表只记录「谁审的、什么结论、命中什么标签、原始返回是什么」，不绑定任何一家厂商的模型。
-- 换供应商时既有记录仍可读，provider 字段区分来源。
--
-- 结论如何影响内容可见性：
--   帖子   pass → status=approved；review → status=pending 转人工；block → status=rejected
--   评论   pass → 公开；review → 仅作者可见并进入人工复核队列；
--          block → deleted_at 置位、deleted_reason='moderation'、deleted_by 留空，仅作者可见
--   标签   pass → 不动；review → 仍然可用，进人工队列；block → 下架（deleted_at），关联行保留
--   图片   写回 image_assets.moderation；block 不可被引用，pending/review 可先引用，
--          但只要还有图片未 pass，所属帖子就不得进入 approved（§5.2.9）
--   ⚠ review 一律是「保持现状 + 进人工队列」，不是「先删了再说」。
--     五类对象在 PRD §6.10.3 的表里语义一致，不要只对某一类对象特殊处理。
-- ============================================================

CREATE TABLE moderation_records (
    id              bigint      PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    -- 审核对象三选一。不用「类型字符串 + 裸 id」的多态写法，那是旧库 likes 表的教训。
    post_id         bigint      REFERENCES posts (id)         ON DELETE CASCADE,
    comment_id      bigint      REFERENCES comments (id)      ON DELETE CASCADE,
    image_asset_id  bigint      REFERENCES image_assets (id)  ON DELETE CASCADE,
    tag_id          bigint      REFERENCES tags (id)          ON DELETE CASCADE,
    -- 用户昵称与个人简介同样是用户输入，同样要审
    user_id         bigint      REFERENCES users (id)         ON DELETE CASCADE,

    -- 帖子与用户有多个可审文本字段，用本列区分审的是哪一段
    field           varchar(32),
    -- 被审内容的版本。复合外键同时锚定「属于哪个对象」，防止指到别的帖子的版本上。
    post_history_id    bigint,
    comment_history_id bigint,

    scene           varchar(16) NOT NULL,
    provider        varchar(32) NOT NULL,
    provider_job_id varchar(128),
    verdict         varchar(16) NOT NULL,
    -- 命中的违规标签。这里用数组而不是字典表：标签取值由外部供应商定义、
    -- 不是用户可见词表、且是一次写入的审计数据，建表没有收益。
    labels          text[]      NOT NULL DEFAULT '{}',
    score           numeric(5,2),
    raw_response    jsonb,
    reviewer_id     bigint      REFERENCES users (id) ON DELETE RESTRICT,
    reviewed_at     timestamptz,
    -- 人工复核不覆盖机审行，而是新插一行 provider='manual' 并用本列指回被复核的机审行
    supersedes_id   bigint      REFERENCES moderation_records (id) ON DELETE RESTRICT,
    created_at      timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT mr_single_target_check
        CHECK (num_nonnulls(post_id, comment_id, image_asset_id, tag_id, user_id) = 1),
    CONSTRAINT mr_scene_check   CHECK (scene IN ('text', 'image')),
    CONSTRAINT mr_verdict_check CHECK (verdict IN ('pass', 'review', 'block')),
    -- 图片只能走图像审核，评论只有文本
    CONSTRAINT mr_scene_target_check
        CHECK (image_asset_id IS NULL OR scene = 'image'),
    CONSTRAINT mr_comment_scene_check
        CHECK (comment_id IS NULL OR scene = 'text'),
    -- 图片是独立的 image_asset 审核对象；其余对象一律只做文本审核
    CONSTRAINT mr_post_scene_check CHECK (post_id IS NULL OR scene = 'text'),
    CONSTRAINT mr_tag_scene_check  CHECK (tag_id  IS NULL OR scene = 'text'),
    CONSTRAINT mr_user_scene_check CHECK (user_id IS NULL OR scene = 'text'),
    -- 用户对象必须指明审的是昵称还是简介
    -- 注意 NULL：field IN (...) 在 field 为 NULL 时求值为 NULL 而非 FALSE，CHECK 会放行，
    -- 所以必须显式加 field IS NOT NULL
    CONSTRAINT mr_user_field_check
        CHECK (user_id IS NULL OR (field IS NOT NULL AND field IN ('name', 'bio'))),
    CONSTRAINT mr_post_field_check
        CHECK (post_id IS NULL OR field IS NULL OR field IN ('title', 'content')),
    -- 版本引用只能出现在对应对象上
    -- 复合外键保证「版本属于这个对象」；但它是 MATCH SIMPLE，
    -- post_id 为 NULL 时会整条跳过，因此仍需下面两条 CHECK 挡住
    -- 「评论的审核记录却带着帖子版本号」这种类型错配。
    CONSTRAINT fk_mr_post_history
        FOREIGN KEY (post_history_id, post_id)
        REFERENCES post_histories (id, post_id) ON DELETE RESTRICT,
    CONSTRAINT fk_mr_comment_history
        FOREIGN KEY (comment_history_id, comment_id)
        REFERENCES comment_histories (id, comment_id) ON DELETE RESTRICT,
    -- 双向成组：帖子/评论的审核结论**必须**指明审的是哪一版，反之版本列也只能出现在对应对象上。
    -- 单向写法（history IS NULL OR 对象 IS NOT NULL）只挡住了「张冠李戴」，
    -- 挡不住「干脆不写版本」，而后者直接违反「每条结论都能回答审的是哪一版」。
    CONSTRAINT mr_post_history_paired_check
        CHECK ((post_id IS NULL) = (post_history_id IS NULL)),
    CONSTRAINT mr_comment_history_paired_check
        CHECK ((comment_id IS NULL) = (comment_history_id IS NULL)),
    CONSTRAINT mr_provider_not_blank_check CHECK (btrim(provider) <> ''),
    CONSTRAINT mr_job_id_not_blank_check
        CHECK (provider_job_id IS NULL OR btrim(provider_job_id) <> ''),
    -- 人工与机器两类记录的字段互斥：人工必须有复核人与时间、不带外部任务号；
    -- 机器记录反之，复核信息一律为空——人工结论要另起一行，不能覆盖机审行。
    CONSTRAINT mr_manual_shape_check CHECK (
        CASE WHEN provider = 'manual'
             THEN reviewer_id IS NOT NULL AND provider_job_id IS NULL
             ELSE reviewer_id IS NULL AND reviewed_at IS NULL
        END
    ),
    CONSTRAINT mr_score_check CHECK (score IS NULL OR (score >= 0 AND score <= 100)),
    -- 人工复核过的必须同时留下人和时间
    CONSTRAINT mr_review_pair_check
        CHECK ((reviewer_id IS NULL) = (reviewed_at IS NULL)),
    CONSTRAINT mr_supersedes_manual_check
        CHECK (supersedes_id IS NULL OR provider = 'manual'),
    CONSTRAINT mr_no_self_supersede_check CHECK (supersedes_id IS DISTINCT FROM id)
);

-- 一条机审记录至多被一条人工记录复核
CREATE UNIQUE INDEX uq_mr_supersedes ON moderation_records (supersedes_id)
    WHERE supersedes_id IS NOT NULL;

CREATE INDEX idx_mr_post    ON moderation_records (post_id, created_at DESC)        WHERE post_id IS NOT NULL;
CREATE INDEX idx_mr_comment ON moderation_records (comment_id, created_at DESC)     WHERE comment_id IS NOT NULL;
CREATE INDEX idx_mr_image   ON moderation_records (image_asset_id, created_at DESC) WHERE image_asset_id IS NOT NULL;
CREATE INDEX idx_mr_tag     ON moderation_records (tag_id, created_at DESC)         WHERE tag_id IS NOT NULL;
CREATE INDEX idx_mr_user    ON moderation_records (user_id, created_at DESC)        WHERE user_id IS NOT NULL;
-- 管理端待复核队列：机审判 review 且尚未被任何人工记录 supersede
-- （是否已被复核需 NOT EXISTS 子查询判定，索引只负责先缩到 review 这一小撮）
CREATE INDEX idx_mr_pending_review ON moderation_records (created_at)
    WHERE verdict = 'review' AND provider <> 'manual';
-- 异步回调按外部任务号对账
CREATE UNIQUE INDEX uq_mr_provider_job ON moderation_records (provider, provider_job_id)
    WHERE provider_job_id IS NOT NULL;
CREATE INDEX idx_mr_labels_gin ON moderation_records USING gin (labels);

-- +goose StatementBegin
CREATE OR REPLACE FUNCTION danshi_forbid_moderation_rewrite()
RETURNS trigger
LANGUAGE plpgsql
AS $func$
BEGIN
  RAISE EXCEPTION
    '审核流水不可覆盖写：人工复核请新插一条 provider=''manual'' 且 supersedes_id 指向机审行的记录'
    USING ERRCODE = 'restrict_violation';
END;
$func$;
-- +goose StatementEnd

-- 「不覆盖写」不能只写在注释里，靠触发器强制。
-- DELETE 同样要挡：删掉审核记录等于销毁追责与申诉的依据。
-- 复用 danshi_forbid_hard_delete，运维物理清除对象时（开逃生阀）仍可级联。
-- 人工复核必须真的「复核那一条机审 review 记录」。
-- 光有「有 supersedes_id 就必须是 manual」远远不够——实测可以写出：
-- manual 行不带 supersedes、复核别的对象的记录、复核 pass 的记录、甚至复核另一条人工行。
-- +goose StatementBegin
CREATE OR REPLACE FUNCTION danshi_check_moderation_review()
RETURNS trigger
LANGUAGE plpgsql
AS $func$
DECLARE t moderation_records%ROWTYPE;
BEGIN
  IF (NEW.provider = 'manual') <> (NEW.supersedes_id IS NOT NULL) THEN
    RAISE EXCEPTION '人工复核记录必须且只能带 supersedes_id，机审记录不得带'
      USING ERRCODE = 'restrict_violation';
  END IF;
  IF NEW.supersedes_id IS NULL THEN
    RETURN NEW;
  END IF;
  SELECT * INTO t FROM moderation_records WHERE id = NEW.supersedes_id FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION '被复核的审核记录不存在' USING ERRCODE = 'restrict_violation';
  END IF;
  IF t.provider = 'manual' THEN
    RAISE EXCEPTION '不能复核另一条人工复核记录' USING ERRCODE = 'restrict_violation';
  END IF;
  IF t.verdict <> 'review' THEN
    RAISE EXCEPTION '只能复核机审判定为 review 的记录，当前被复核记录 verdict=%', t.verdict
      USING ERRCODE = 'restrict_violation';
  END IF;
  IF (NEW.post_id, NEW.comment_id, NEW.image_asset_id, NEW.tag_id, NEW.user_id,
      NEW.scene, NEW.field, NEW.post_history_id, NEW.comment_history_id)
     IS DISTINCT FROM
     (t.post_id, t.comment_id, t.image_asset_id, t.tag_id, t.user_id,
      t.scene, t.field, t.post_history_id, t.comment_history_id) THEN
    RAISE EXCEPTION '人工复核必须针对同一对象、同一字段、同一版本'
      USING ERRCODE = 'restrict_violation';
  END IF;
  RETURN NEW;
END;
$func$;
-- +goose StatementEnd

CREATE TRIGGER trg_moderation_records_check_review
    BEFORE INSERT ON moderation_records
    FOR EACH ROW EXECUTE FUNCTION danshi_check_moderation_review();

CREATE TRIGGER trg_moderation_records_immutable
    BEFORE UPDATE ON moderation_records
    FOR EACH ROW EXECUTE FUNCTION danshi_forbid_moderation_rewrite();
CREATE TRIGGER trg_moderation_records_forbid_delete
