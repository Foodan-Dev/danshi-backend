CREATE TABLE notifications (
    id                 bigint      PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    recipient_id       bigint      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    sender_id          bigint      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    type               varchar(20) NOT NULL,
    -- 旧库是 related_id(裸 uuid) + related_type，无外键，实测已有 2 条悬挂通知。
    related_post_id    bigint      REFERENCES posts (id) ON DELETE CASCADE,
    related_comment_id bigint      REFERENCES comments (id) ON DELETE CASCADE,
    content            varchar(100),
    is_read            boolean     NOT NULL DEFAULT false,
    created_at         timestamptz NOT NULL DEFAULT now(),
    updated_at         timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT notifications_type_check
        CHECK (type IN ('like_post', 'like_comment', 'comment', 'reply', 'mention', 'follow')),
    -- 关联目标由 type 唯一决定，比「至多一个」更严：
    --   like_post / comment            → 只能关联帖子
    --   like_comment / reply / mention → 只能关联评论
    --   follow                         → 两者都必须为空
    CONSTRAINT notifications_target_matches_type_check CHECK (
        CASE type
            WHEN 'like_post'    THEN related_post_id IS NOT NULL AND related_comment_id IS NULL
            WHEN 'comment'      THEN related_post_id IS NOT NULL AND related_comment_id IS NULL
            WHEN 'like_comment' THEN related_comment_id IS NOT NULL AND related_post_id IS NULL
            WHEN 'reply'        THEN related_comment_id IS NOT NULL AND related_post_id IS NULL
            WHEN 'mention'      THEN related_comment_id IS NOT NULL AND related_post_id IS NULL
            WHEN 'follow'       THEN related_post_id IS NULL AND related_comment_id IS NULL
        END
    ),
    -- 正文预览只属于「有话可引」的三类通知；点赞与关注不该带预览。
    -- PRD 的通知表把这一列写死了有无，数据库就该守住，否则前端渲染会出现空预览框。
    CONSTRAINT notifications_content_matches_type_check CHECK (
        CASE WHEN type IN ('comment', 'reply', 'mention')
             THEN content IS NOT NULL AND btrim(content) <> ''
             ELSE content IS NULL
        END
    )
);

CREATE INDEX idx_notifications_recipient_created ON notifications (recipient_id, created_at DESC);
CREATE INDEX idx_notifications_recipient_unread  ON notifications (recipient_id)
    WHERE is_read = false;

