-- ============================================================
-- dictionary_suggestions：用户提议词条 → 管理员审核 → 入库并回绑帖子
--
-- 口味 / 菜系 / 餐厅 / 窗口是后端写死的受控词表，用户只能选不能填。
-- 但词表不可能一次穷尽（新窗口、新菜系随时出现），所以提供提议通道：
--
--   1. 用户发帖时发现没有合适的词条，提交一条 suggestion（可携带来源帖子 id）
--   2. 管理员在后台看到 pending 列表
--   3. 通过 → 在对应字典表创建条目，回填 resulting_*_id，
--      并按 kind 把新条目绑回 post_id 指向的帖子
--   4. 驳回 → status=rejected，review_note 说明原因
--
-- 一张表覆盖四种词表，靠 kind 区分；resulting_* 用四个可空外键而不是
-- 「一个裸 id + kind」，是为了保住引用完整性（这正是旧库多态 likes 表的教训）。
-- ============================================================

CREATE TABLE dictionary_suggestions (
    id                bigint       PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    kind              varchar(20)  NOT NULL,
    proposed_name     varchar(100) NOT NULL,
    -- 审核历史必须留存：用 RESTRICT，避免物理清除用户时连带抹掉其全部提议与审核结论。
    -- 用户注销是软删除，正常路径不会触发本约束。
    proposer_id       bigint       NOT NULL REFERENCES users (id) ON DELETE RESTRICT,
    -- 来源帖子。审核通过后把新词条绑回这个帖子；帖子被删则置空，提议本身仍可入库。
    post_id           bigint       REFERENCES posts (id) ON DELETE SET NULL,
    -- kind='flavor' 时必填：新口味绑回帖子时用哪种立场
    flavor_stance     varchar(10),
    -- kind='canteen_window' 时二选一（也可先后都有）：新窗口挂在哪个餐厅下。
    --   parent_canteen_id    —— 挂到一个**已存在**的餐厅
    --   parent_suggestion_id —— 挂到一条同批提交的 kind='canteen' 提议上，
    --                           用于「餐厅和窗口一起提议」：用户发现整个餐厅都没收录时，
    --                           先提餐厅、再提它下面的窗口，两条提议一起进待审列表。
    -- 审核顺序必须是先批餐厅、再批窗口；批窗口时把 parent_canteen_id 补成刚建出的餐厅 id
    -- （ds_parent_canteen_check 要求 approved 时它必须非空），这样下方复合外键才有效。
    parent_canteen_id bigint       REFERENCES canteens (id) ON DELETE RESTRICT,
    parent_suggestion_id bigint,
    -- 生成列：仅用于把 parent_suggestion_id 约束到 kind='canteen' 的提议上
    parent_suggestion_kind varchar(20) GENERATED ALWAYS AS
        (CASE WHEN parent_suggestion_id IS NULL THEN NULL ELSE 'canteen' END) STORED,

    status            varchar(20)  NOT NULL DEFAULT 'pending',
    reviewer_id       bigint       REFERENCES users (id) ON DELETE SET NULL,
    reviewed_at       timestamptz,
    review_note       text,

    -- 通过后指向实际创建（或复用）的字典条目，四选一且必须与 kind 匹配。
    -- 用 RESTRICT 而非 SET NULL：SET NULL 会把 approved 行的产出抹成空，
    -- 直接违反下方 ds_resulting_check，导致管理端删词条时报一个莫名其妙的约束错误。
    -- 语义上也应该是「被审核历史引用的词条不能物理删除，只能 is_active=false」。
    resulting_flavor_id  bigint REFERENCES flavors (id)         ON DELETE RESTRICT,
    resulting_cuisine_id bigint REFERENCES cuisines (id)        ON DELETE RESTRICT,
    resulting_canteen_id bigint REFERENCES canteens (id)        ON DELETE RESTRICT,
    resulting_window_id  bigint,

    created_at        timestamptz  NOT NULL DEFAULT now(),
    updated_at        timestamptz  NOT NULL DEFAULT now(),

    CONSTRAINT ds_kind_check   CHECK (kind IN ('flavor', 'cuisine', 'canteen', 'canteen_window')),
    CONSTRAINT ds_status_check CHECK (status IN ('pending', 'approved', 'rejected')),
    CONSTRAINT ds_name_trimmed_check
        CHECK (proposed_name = btrim(proposed_name) AND btrim(proposed_name) <> ''),

    -- kind 决定哪些辅助字段必填
    CONSTRAINT ds_flavor_stance_check
        CHECK ((kind = 'flavor') = (flavor_stance IS NOT NULL)),
    CONSTRAINT ds_flavor_stance_enum_check
        CHECK (flavor_stance IS NULL OR flavor_stance IN ('has', 'prefer', 'avoid')),
    -- 窗口提议必须指明父餐厅：已存在的餐厅、或同批提交的餐厅提议，至少有一个。
    -- 审核通过时 parent_canteen_id 必须已落实（否则 fk_ds_resulting_window 形同虚设）。
    CONSTRAINT ds_parent_canteen_check CHECK (
        CASE WHEN kind = 'canteen_window'
             THEN num_nonnulls(parent_canteen_id, parent_suggestion_id) >= 1
                  AND (status <> 'approved' OR parent_canteen_id IS NOT NULL)
             ELSE parent_canteen_id IS NULL AND parent_suggestion_id IS NULL
        END
    ),
    CONSTRAINT ds_no_self_parent_check CHECK (parent_suggestion_id IS DISTINCT FROM id),
    -- 父提议必须是一条餐厅提议，不能把窗口挂到口味/菜系提议上
    CONSTRAINT uq_ds_id_kind UNIQUE (id, kind),
    CONSTRAINT fk_ds_parent_suggestion
        FOREIGN KEY (parent_suggestion_id, parent_suggestion_kind)
        REFERENCES dictionary_suggestions (id, kind) ON DELETE RESTRICT,
    -- 光约束「父提议是餐厅提议」还不够：曾经可以写出「窗口提议挂在 A 餐厅提议上，
    -- 却把窗口批到 B 餐厅」的错配状态，以及「父提议还是 pending 就先批了子提议」。
    -- 下面这条复合外键把两个洞一起堵上：
    --   parent_canteen_id 必须等于父提议实际批出来的那个餐厅。
    --   父提议未批准时 resulting_canteen_id 为空，配不上任何非空值 ⇒ 子提议批不了。
    --   pending 阶段子提议的 parent_canteen_id 为空 ⇒ MATCH SIMPLE 跳过，不妨碍先提交。
    CONSTRAINT uq_ds_id_resulting_canteen UNIQUE (id, resulting_canteen_id),
    CONSTRAINT fk_ds_parent_resulting_canteen
        FOREIGN KEY (parent_suggestion_id, parent_canteen_id)
        REFERENCES dictionary_suggestions (id, resulting_canteen_id) ON DELETE RESTRICT,
    -- 批出来的窗口必须真的挂在提议时指定的那个餐厅下
    CONSTRAINT fk_ds_resulting_window
        FOREIGN KEY (resulting_window_id, parent_canteen_id)
        REFERENCES canteen_windows (id, canteen_id) ON DELETE RESTRICT,

    -- pending：审核人与时间都必须为空；approved/rejected：两者都必须有值。
    -- 写成等式 `(status='pending') = (reviewer_id IS NULL AND reviewed_at IS NULL)` 是不够的——
    -- 那样非 pending 时只要求「不同时为空」，可以只有审核人没有时间。
    CONSTRAINT ds_review_fields_check CHECK (
        CASE WHEN status = 'pending'
             THEN reviewer_id IS NULL     AND reviewed_at IS NULL
             ELSE reviewer_id IS NOT NULL AND reviewed_at IS NOT NULL
        END
    ),
    -- 驳回必须说明理由
    CONSTRAINT ds_reject_note_check
        CHECK (status <> 'rejected' OR btrim(coalesce(review_note, '')) <> ''),

    -- 只有 approved 才有产出，且产出类型必须与 kind 对应
    CONSTRAINT ds_resulting_check CHECK (
        CASE WHEN status = 'approved' THEN
            num_nonnulls(resulting_flavor_id, resulting_cuisine_id,
                         resulting_canteen_id, resulting_window_id) = 1
            AND (kind <> 'flavor'         OR resulting_flavor_id  IS NOT NULL)
            AND (kind <> 'cuisine'        OR resulting_cuisine_id IS NOT NULL)
            AND (kind <> 'canteen'        OR resulting_canteen_id IS NOT NULL)
            AND (kind <> 'canteen_window' OR resulting_window_id  IS NOT NULL)
        ELSE
            num_nonnulls(resulting_flavor_id, resulting_cuisine_id,
                         resulting_canteen_id, resulting_window_id) = 0
        END
    )
);

