CREATE OR REPLACE FUNCTION danshi_sync_post_like_count()
RETURNS trigger
LANGUAGE plpgsql
AS $func$
DECLARE prev text;
BEGIN
  -- 保存并恢复，而不是只置位：set_config 的第三参数是「事务局部」不是「函数局部」，
  -- 只置位会让 GUC 一直留到事务结束，同一个 HTTP 事务里后续任何直接写计数都会被放行。
  prev := current_setting('danshi.allow_counter_write', true);
  PERFORM set_config('danshi.allow_counter_write', 'on', true);
  IF TG_OP = 'INSERT' THEN
    UPDATE posts SET like_count = like_count + 1 WHERE id = NEW.post_id;
    PERFORM set_config('danshi.allow_counter_write', COALESCE(prev, ''), true);
    RETURN NEW;
  END IF;
  UPDATE posts SET like_count = GREATEST(like_count - 1, 0) WHERE id = OLD.post_id;
  PERFORM set_config('danshi.allow_counter_write', COALESCE(prev, ''), true);
  RETURN OLD;
END;
$func$;
-- +goose StatementEnd

