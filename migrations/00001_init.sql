-- ============================================================
-- comments
-- ============================================================

-- 存储保留真实回复链（可任意深），展示时按 root 拍扁成两层。
--
-- 三种写入行为：
--   1. 点帖子的评论按钮        → parent_id = NULL,           root_id = NULL,
--                                reply_to_user_id = post.author_id
--   2. 点某条 root 评论的回复  → parent_id = root.id,        root_id = root.id,
--                                reply_to_user_id = parent.author_id
--   3. 点某条非 root 评论的回复 → parent_id = parent.id,      root_id = parent.root_id,
--                                reply_to_user_id = parent.author_id
--
-- 也就是：parent_id 记录「回复的是谁」，root_id 记录「挂在哪个楼下」。
-- 前端只需按 root_id 分组即可拍扁呈现，无需递归；后端保留 parent 链以便日后
-- 需要还原真实层级或做「回复 @某人」溯源。
--
-- 三条不变式全部由一个复合外键声明式保证，不依赖应用层自觉：
--   (a) parent 与 root 必须同时为空或同时非空（要么是根评论，要么是回复）
--   (b) 回复必须与父评论在同一帖子下 —— 否则 reply_count 记在 A 帖、
--       comment_count 记在 B 帖，计数器会写出无法解释的数据
--   (c) 回复的 root_id 必须等于父评论所在的楼 —— 防止把回复挂到别的楼下
--
-- 做法：生成列 effective_root_id = COALESCE(root_id, id)，
-- 即「这一行属于哪个楼」（根评论属于自己那一楼）。
-- 外键 (parent_id, post_id, root_id) → (id, post_id, effective_root_id)：
--   · 根评论两列皆 NULL → MATCH SIMPLE 跳过检查
--   · 回复 root  评论 R：要求存在 (R.id, 同帖, R.id)      —— R 的 effective_root 就是自己 ✓
--   · 回复非 root 评论 C：要求存在 (C.id, 同帖, C.root_id) —— 楼号必须与 C 一致 ✓
CREATE TABLE comments (
    id               bigint      PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    post_id          bigint      NOT NULL REFERENCES posts (id) ON DELETE CASCADE,
    author_id        bigint      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    parent_id        bigint,
    root_id          bigint,
    -- 「回复某人」不能随便填：楼主评论指向帖子作者，回复指向父评论作者。
    -- 这个字段影响渲染（「回复 张三：」）与通知投递，填错就是可见的错误状态。
    -- 用复合外键锚定，不依赖服务层自觉——见表末尾两条 fk_comments_reply_to_*。
    reply_to_user_id bigint      NOT NULL REFERENCES users (id) ON DELETE RESTRICT,
    content          text        NOT NULL,
    like_count       integer     NOT NULL DEFAULT 0,
    reply_count      integer     NOT NULL DEFAULT 0,
    -- 软删除：删一条评论不能连带毁掉挂在它下面的别人的回复，
    -- 因此删除只打标记、保留行；公开查询整条过滤，不渲染占位。
    -- content 不清空，管理员复核时要能看到原文。
    deleted_at       timestamptz,
    deleted_reason   varchar(16),
    deleted_by       bigint      REFERENCES users (id) ON DELETE RESTRICT,
    created_at       timestamptz NOT NULL DEFAULT now(),
    updated_at       timestamptz NOT NULL DEFAULT now(),

    -- 「这一行属于哪个楼」：根评论是自己，回复是它的 root
    effective_root_id bigint GENERATED ALWAYS AS (COALESCE(root_id, id)) STORED,
    -- 仅楼主评论有值，用于把 reply_to_user_id 锚定到帖子作者；回复行为 NULL 时复合外键跳过
    root_post_id_for_author_check bigint GENERATED ALWAYS AS
        (CASE WHEN parent_id IS NULL THEN post_id ELSE NULL END) STORED,

    CONSTRAINT comments_not_self_parent_check CHECK (parent_id IS DISTINCT FROM id),
    CONSTRAINT comments_not_self_root_check   CHECK (root_id   IS DISTINCT FROM id),
    -- 三者成组：未删除时不得残留删除信息，已删除时来源必填
    CONSTRAINT comments_delete_pair_check CHECK (
        CASE WHEN deleted_at IS NULL
             THEN deleted_reason IS NULL AND deleted_by IS NULL
             ELSE deleted_reason IS NOT NULL
        END
    ),
    CONSTRAINT comments_delete_reason_check
        CHECK (deleted_reason IS NULL OR deleted_reason IN ('author', 'admin', 'moderation')),
    CONSTRAINT comments_root_pair_check       CHECK ((parent_id IS NULL) = (root_id IS NULL)),
    CONSTRAINT comments_counters_check        CHECK (like_count >= 0 AND reply_count >= 0),
    -- reply_count 只在楼主评论上有意义（整层楼的回复数），回复行恒为 0
    CONSTRAINT comments_reply_count_root_only_check
        CHECK (root_id IS NULL OR reply_count = 0),

    -- 被下方复合外键引用，PostgreSQL 要求引用目标列组有唯一约束
    CONSTRAINT uq_comments_id_post_root UNIQUE (id, post_id, effective_root_id),
    CONSTRAINT fk_comments_parent
        FOREIGN KEY (parent_id, post_id, root_id)
        REFERENCES comments (id, post_id, effective_root_id) ON DELETE CASCADE,

    -- 楼主评论（parent_id 为空）：reply_to_user_id 必须是帖子作者。
    -- 生成列在无父时回填 post_id，有父时为 NULL，让 MATCH SIMPLE 只在楼主评论上生效。
    CONSTRAINT fk_comments_reply_to_post_author
        FOREIGN KEY (root_post_id_for_author_check, reply_to_user_id)
        REFERENCES posts (id, author_id) ON DELETE RESTRICT,
    -- 回复：reply_to_user_id 必须是父评论作者
    CONSTRAINT fk_comments_reply_to_parent_author
        FOREIGN KEY (parent_id, reply_to_user_id)
        REFERENCES comments (id, author_id) ON DELETE RESTRICT,
    CONSTRAINT uq_comments_id_author UNIQUE (id, author_id)
);

-- 取某帖的楼主评论列表
CREATE INDEX idx_comments_post_roots ON comments (post_id, created_at DESC)
    WHERE root_id IS NULL;
-- 取某一楼的全部回复（拍扁呈现用，按时间正序）
CREATE INDEX idx_comments_root_created ON comments (root_id, created_at)
    WHERE root_id IS NOT NULL;
-- 管理端复核被机审删掉的评论
CREATE INDEX idx_comments_deleted ON comments (deleted_at DESC)
