-- 反规范化计数器：由触发器维护
--
-- 旧库由应用层维护，实测 31 篇帖子中 16 篇 like_count 与源表对不上且一律偏低。
-- 计数器是纯机械派生（值就是 COUNT(*)），交给数据库维护才能与源表同事务一致。
--
-- 这些触发器只写计数列，不碰 updated_at——本 schema 已无 updated_at 触发器，
-- 所以点赞、收藏、评论天然不会污染帖子的「内容编辑时间」。
--
-- 同步函数只处理 INSERT / DELETE。若关联键可以被 UPDATE（把一条点赞从帖子 A 改到帖子 B），
-- 两边计数都会永久漂移且无人察觉。因此下面先把这些关联键声明为**不可变**：
-- 需要「换个目标」时必须删除后重建，这样走的仍是 INSERT/DELETE 路径。
-- ============================================================

