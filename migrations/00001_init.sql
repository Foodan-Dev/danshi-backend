-- ------------------------------------------------------------
-- image_assets：禁止物理删除（沿用 Python 版本的防线）
-- ------------------------------------------------------------

-- +goose StatementBegin
CREATE OR REPLACE FUNCTION danshi_forbid_image_asset_delete()
RETURNS trigger
LANGUAGE plpgsql
AS $func$
BEGIN
  IF current_setting('danshi.allow_image_asset_delete', true)
     IS NOT DISTINCT FROM 'on' THEN
    RETURN OLD;
  END IF;
  RAISE EXCEPTION
    'image_assets 不允许物理删除。业务删除请将 status 标为 retired；'
    '运维删除请在同一事务内 SET LOCAL danshi.allow_image_asset_delete = ''on''，'
    '或调用 danshi_purge_image_assets(bigint[])'
    USING ERRCODE = 'restrict_violation';
END;
$func$;
-- +goose StatementEnd

CREATE TRIGGER trg_image_assets_forbid_delete
    BEFORE DELETE ON image_assets
    FOR EACH ROW EXECUTE FUNCTION danshi_forbid_image_asset_delete();

-- +goose StatementBegin
CREATE OR REPLACE FUNCTION danshi_purge_image_assets(p_ids bigint[])
RETURNS integer
LANGUAGE plpgsql
AS $func$
DECLARE
  deleted_count integer;
  prev_asset    text;
  prev_hard     text;
BEGIN
  -- 两个逃生阀都要开：删资产会经 CASCADE 带走它的审核流水，
  -- 而审核流水的禁删触发器看的是 danshi.allow_hard_delete。
  -- Grandfather 上线后每张历史图片都有审核记录，不开这个阀 purge 会全线失败。
  prev_asset := current_setting('danshi.allow_image_asset_delete', true);
  prev_hard  := current_setting('danshi.allow_hard_delete', true);
  PERFORM set_config('danshi.allow_image_asset_delete', 'on', true);
  PERFORM set_config('danshi.allow_hard_delete', 'on', true);

  DELETE FROM image_assets WHERE id = ANY (p_ids);
  GET DIAGNOSTICS deleted_count = ROW_COUNT;

  -- 保存并恢复，不能只置位：set_config 的第三参数是事务局部不是函数局部，
  -- 只置位会让后续任意资产删除、任意审计表删除在同一事务里全部放行。
  PERFORM set_config('danshi.allow_image_asset_delete', COALESCE(prev_asset, ''), true);
  PERFORM set_config('danshi.allow_hard_delete', COALESCE(prev_hard, ''), true);
  RETURN deleted_count;
END;
$func$;
-- +goose StatementEnd

COMMENT ON FUNCTION danshi_purge_image_assets(bigint[]) IS
  '运维通道：真正删除资产行。仅在远端对象已删除后调用。';


