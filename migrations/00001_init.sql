-- 供 ETL 与 CI 一致性断言使用：全量重算所有计数器，返回被修正的行数。
-- +goose StatementBegin
CREATE OR REPLACE FUNCTION danshi_recount_all()
RETURNS TABLE (table_name text, fixed_rows bigint)
LANGUAGE plpgsql
AS $func$
DECLARE
  n bigint;
  prev text;
BEGIN
  prev := current_setting('danshi.allow_counter_write', true);
  PERFORM set_config('danshi.allow_counter_write', 'on', true);
  WITH actual AS (
    SELECT p.id,
           (SELECT count(*) FROM post_likes  pl WHERE pl.post_id = p.id) AS lc,
           (SELECT count(*) FROM favorites   f  WHERE f.post_id  = p.id) AS fc,
           (SELECT count(*) FROM comments    c  WHERE c.post_id  = p.id
                                               AND c.deleted_at IS NULL) AS cc
    FROM posts p
  ), upd AS (
    UPDATE posts p
       SET like_count = a.lc, favorite_count = a.fc, comment_count = a.cc
      FROM actual a
     WHERE p.id = a.id
       AND (p.like_count, p.favorite_count, p.comment_count) IS DISTINCT FROM (a.lc, a.fc, a.cc)
    RETURNING 1
  ) SELECT count(*) INTO n FROM upd;
  table_name := 'posts'; fixed_rows := n; RETURN NEXT;

  WITH actual AS (
    SELECT c.id,
           (SELECT count(*) FROM comment_likes cl WHERE cl.comment_id = c.id) AS lc,
           (SELECT count(*) FROM comments       r WHERE r.root_id      = c.id
                                                    AND r.deleted_at IS NULL) AS rc
    FROM comments c
  ), upd AS (
    UPDATE comments c
       SET like_count = a.lc, reply_count = a.rc
      FROM actual a
     WHERE c.id = a.id
       AND (c.like_count, c.reply_count) IS DISTINCT FROM (a.lc, a.rc)
    RETURNING 1
  ) SELECT count(*) INTO n FROM upd;
  table_name := 'comments'; fixed_rows := n; RETURN NEXT;
  PERFORM set_config('danshi.allow_counter_write', COALESCE(prev, ''), true);
END;
$func$;
-- +goose StatementEnd

COMMENT ON FUNCTION danshi_recount_all() IS
  'ETL 装载完成后必须调用一次；CI 一致性断言应断言其返回的 fixed_rows 全为 0。'
  '因 schema 无 updated_at 触发器，重算不会污染业务时间戳。';


-- ============================================================
-- 图片资产退役：由外键关系驱动，不再做 URL 字符串匹配
-- ============================================================

-- +goose StatementBegin
CREATE OR REPLACE FUNCTION danshi_retire_asset_if_unreferenced(p_asset_id bigint)
RETURNS void
LANGUAGE plpgsql
AS $func$
BEGIN
  IF p_asset_id IS NULL THEN
    RETURN;
  END IF;
  -- 这里显式写 updated_at：资产状态流转是本函数自己的业务语义，
  -- 与被移除的通用 updated_at 触发器无关。
  UPDATE image_assets AS a
     SET status = 'retired', updated_at = now()
   WHERE a.id = p_asset_id
     AND a.status = 'ready'
     AND NOT EXISTS (SELECT 1 FROM post_images pi WHERE pi.image_asset_id = a.id)
     AND NOT EXISTS (SELECT 1 FROM users u WHERE u.avatar_image_asset_id = a.id);
END;
$func$;
-- +goose StatementEnd

-- +goose StatementBegin
CREATE OR REPLACE FUNCTION danshi_retire_post_image_asset()
RETURNS trigger
LANGUAGE plpgsql
AS $func$
BEGIN
  PERFORM danshi_retire_asset_if_unreferenced(OLD.image_asset_id);
  RETURN OLD;
END;
$func$;
-- +goose StatementEnd

CREATE TRIGGER trg_post_images_retire_asset
    AFTER DELETE ON post_images
    FOR EACH ROW EXECUTE FUNCTION danshi_retire_post_image_asset();

-- 反方向：重新引用一张已退役的资产时要让它复活，否则「删除后可再次创建」
-- 在行级成立、在资产状态上却是错的（实测删→retired→再插入仍是 retired）。
-- +goose StatementBegin
CREATE OR REPLACE FUNCTION danshi_activate_post_image_asset()
RETURNS trigger
LANGUAGE plpgsql
AS $func$
BEGIN
  UPDATE image_assets
     SET status = 'ready', updated_at = now()
   WHERE id = NEW.image_asset_id
     AND status <> 'ready';
  RETURN NEW;
END;
$func$;
-- +goose StatementEnd

CREATE TRIGGER trg_post_images_activate_asset
    AFTER INSERT ON post_images
    FOR EACH ROW EXECUTE FUNCTION danshi_activate_post_image_asset();

-- 关联键不可变：改 image_asset_id 会绕过旧资产的退役检查。换图请删除后重建。
CREATE TRIGGER trg_post_images_keys_immutable
    BEFORE UPDATE OF post_id, image_asset_id ON post_images
    FOR EACH ROW
    WHEN (OLD.post_id IS DISTINCT FROM NEW.post_id
       OR OLD.image_asset_id IS DISTINCT FROM NEW.image_asset_id)
    EXECUTE FUNCTION danshi_forbid_key_update();

-- +goose StatementBegin
CREATE OR REPLACE FUNCTION danshi_retire_avatar_asset()
RETURNS trigger
LANGUAGE plpgsql
AS $func$
BEGIN
  IF TG_OP = 'DELETE' THEN
    PERFORM danshi_retire_asset_if_unreferenced(OLD.avatar_image_asset_id);
    RETURN OLD;
  END IF;
  IF OLD.avatar_image_asset_id IS DISTINCT FROM NEW.avatar_image_asset_id THEN
    PERFORM danshi_retire_asset_if_unreferenced(OLD.avatar_image_asset_id);
  END IF;
  RETURN NEW;
END;
$func$;
-- +goose StatementEnd

CREATE TRIGGER trg_users_retire_avatar_asset
    AFTER UPDATE OF avatar_image_asset_id OR DELETE ON users
    FOR EACH ROW EXECUTE FUNCTION danshi_retire_avatar_asset();


