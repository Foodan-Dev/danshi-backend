-- +goose StatementBegin
CREATE OR REPLACE FUNCTION danshi_check_suggestion_transition()
RETURNS trigger
LANGUAGE plpgsql
AS $func$
BEGIN
  IF OLD.status <> 'pending' THEN
    IF NEW.status <> OLD.status THEN
      RAISE EXCEPTION '提议已是终态 %，不可再变更为 %；需要改判请另建提议',
        OLD.status, NEW.status USING ERRCODE = 'restrict_violation';
    END IF;
    -- 终态冻结**全部**业务与审计字段，不只是审核结论与产出。
    -- 早先漏掉 post_id / flavor_stance / 父提议 / 父餐厅 / created_at，
    -- 结果可以把一条已批准的提议改绑到另一篇帖子、改掉已审过的口味立场。
    IF (NEW.kind, NEW.proposed_name, NEW.proposer_id, NEW.reviewer_id, NEW.reviewed_at,
        NEW.review_note, NEW.resulting_flavor_id, NEW.resulting_cuisine_id,
        NEW.resulting_canteen_id, NEW.resulting_window_id,
        NEW.flavor_stance, NEW.parent_canteen_id, NEW.parent_suggestion_id, NEW.created_at)
       IS DISTINCT FROM
       (OLD.kind, OLD.proposed_name, OLD.proposer_id, OLD.reviewer_id, OLD.reviewed_at,
        OLD.review_note, OLD.resulting_flavor_id, OLD.resulting_cuisine_id,
        OLD.resulting_canteen_id, OLD.resulting_window_id,
        OLD.flavor_stance, OLD.parent_canteen_id, OLD.parent_suggestion_id, OLD.created_at) THEN
      RAISE EXCEPTION '终态提议的内容、审核结论与产出均不可篡改' USING ERRCODE = 'restrict_violation';
    END IF;
    -- post_id 例外：来源帖被物理清除时 ON DELETE SET NULL 会把它置空，这是合法的；
    -- 但不允许改绑到另一篇帖子。
    IF NEW.post_id IS DISTINCT FROM OLD.post_id AND NEW.post_id IS NOT NULL THEN
      RAISE EXCEPTION '终态提议不可改绑来源帖子' USING ERRCODE = 'restrict_violation';
    END IF;
  END IF;
  RETURN NEW;
END;
$func$;
-- +goose StatementEnd

