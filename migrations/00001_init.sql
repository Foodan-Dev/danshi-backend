-- Danshi Go 后端初始 schema
--
-- 目标：PostgreSQL 18。不使用 GORM AutoMigrate，本文件是 schema 唯一真源。
--
-- ============================================================================
-- 设计原则 1：数据库负责「机械派生」，应用层负责「语义判断」
-- ============================================================================
--
-- updated_at 是语义字段——「内容被编辑」只有业务代码知道算不算。点赞、收藏、
-- 浏览、后台重算计数器都不该动它。因此本 schema **不含任何 updated_at 触发器**，
-- 一律由 GORM 的 autoUpdateTime 在业务写入时维护。
--   ⚠ 推论：view_count 自增等「非内容变更」的写入必须用 GORM 的 UpdateColumn
--     （跳过 hook 与 autoUpdateTime），不能用 Update / Updates。
--
-- 计数器（like_count 等）相反，是纯机械派生：值就是 COUNT(*)，没有语义空间。
-- 旧库交给应用层维护的结果是 31 篇帖子中 16 篇 like_count 漂移且一律偏低，
-- 所以这部分保留触发器，保证与源表同事务一致。
--
-- ============================================================================
-- 设计原则 2：主键一律 bigint identity
-- ============================================================================
--
-- 所有代理主键为 `bigint GENERATED BY DEFAULT AS IDENTITY`，对应 GORM 默认的
-- `ID uint64` 约定。相比 uuid：索引宽度 8 字节而非 16、连接与排序更快、
-- 自增写入天然聚集在 B-tree 右端。
--
-- 用 BY DEFAULT 而非 ALWAYS，是为了让 ETL 能显式指定 id 装载
-- （装载完必须 setval 推进序列，见 data-migration-plan.md §3 与 §5）。
--
--   ⚠ 已知代价：id 可枚举。用户 id 泄露注册总数与注册顺序，帖子 id 可被顺序遍历。
--     内容本身是公开的，但草稿 / 待审帖子的 id 也会落在可枚举区间内，
--     因此**所有按 id 取详情的接口都必须做鉴权，不能依赖 id 不可猜**。
--
-- ============================================================================
-- 相较 Python/Alembic 版本的结构性变更（详见 docs/go-rewrite-plan.md §5.2）
-- ============================================================================
--   1. 全部 uuid 主键          → bigint identity
--   2. tags JSONB              → tags + post_tags 关联表（标签名限 10 字符）
--   3. flavors / preferences JSONB → flavors 字典表 + post_flavors(stance)
--   4. canteen / cuisine 自由文本  → canteens / canteen_windows / cuisines 字典表
--   5. posts.budget_range JSONB    → budget_min / budget_max 列
--   6. posts.images JSONB(URL)     → post_images 关联表 + 真外键
--   7. comments.mentioned_user_ids JSONB → comment_mentions 关联表
--   8. users.avatar_url(text)      → users.avatar_image_asset_id 真外键
--   9. 多态 likes 表               → post_likes / comment_likes + 真外键
--  10. notifications.related_id    → related_post_id / related_comment_id 外键
--  11. notifications.content       → 保留并限长 varchar(100)；type 补 'mention'；
--                                    关联目标由 type 唯一决定（比旧库的 related_type 严格）
--  12. users.hometown              → 删除（无任何读取逻辑的展示字段）
--  13. 计数器改触发器维护；updated_at 触发器全部移除
--  14. 新增 dictionary_suggestions：用户提议词条 → 管理员审核 → 入库并回绑帖子
--  15. 新增 user_sessions：令牌绑定会话，撤销立即生效（旧 logout 是空壳）
--  16. comments 增加 root_id：存真实回复链，展示按楼拍扁；reply_count 改按 root 统计
--  17. comments 软删除：删评论不再连带毁掉他人的回复
--  18. users.is_active → banned_until/ban_reason/banned_by：支持限时封禁
--  19. 新增 moderation_records + image_assets.moderation：机器内容审核，供应商可替换
--  20. users / posts / comments / tags 一律软删除，物理删除由触发器拒绝
--  21. 新增 post_histories / comment_histories：帖子与评论可编辑，逐版保留快照
--  22. 审核覆盖扩展到话题标签与用户昵称/简介；帖子先审后发，其余先发后审

-- +goose Up

-- ============================================================
-- 通用：禁止物理删除
--
-- 产品要求「所有内容一律软删除」。软删除若只是应用层约定，迟早会被一条手写 SQL
-- 或一次误操作绕过，因此和 image_assets 一样用触发器强制：
-- users / posts / comments / tags 的 DELETE 一律拒绝，只能置 deleted_at。
--
-- 运维确需物理清除时，在同一事务内 SET LOCAL danshi.allow_hard_delete = 'on'。
-- 这是事务局部的，不需要表 owner 权限，也不会取 ACCESS EXCLUSIVE 锁。
--
-- ⚠ 关联表（post_likes / favorites / follows / post_tags / post_flavors / post_images
--   / comment_mentions）**不在此列**，它们是「动作」不是「内容」：
--   取消点赞就该真的删行——复合主键决定了软删的行会永久占位、让用户无法再次点赞。
-- ============================================================

-- +goose StatementBegin
CREATE OR REPLACE FUNCTION danshi_forbid_row_update()
RETURNS trigger
LANGUAGE plpgsql
AS $func$
BEGIN
  RAISE EXCEPTION
    '% 是追加不可篡改的记录，禁止修改。需要更正请追加新记录并指向被更正的那一条。', TG_TABLE_NAME
    USING ERRCODE = 'restrict_violation';
END;
$func$;
-- +goose StatementEnd

-- +goose StatementBegin
CREATE OR REPLACE FUNCTION danshi_forbid_hard_delete()
RETURNS trigger
LANGUAGE plpgsql
AS $func$
BEGIN
  IF current_setting('danshi.allow_hard_delete', true) IS NOT DISTINCT FROM 'on' THEN
    RETURN OLD;
  END IF;
  RAISE EXCEPTION
    '% 不允许物理删除（内容表请改为软删除，审计表本就只能追加）；'
    '运维清除请在同一事务内 SET LOCAL danshi.allow_hard_delete = ''on''', TG_TABLE_NAME
    USING ERRCODE = 'restrict_violation';
END;
$func$;
-- +goose StatementEnd


-- ============================================================
-- 字典表：canteens / canteen_windows / cuisines / flavors
--
-- 这些旧库是帖子上的自由文本列，前端 config_service.ts 里另有一份硬编码
-- 词表（且后端从未提供 /config 端点，四个 fetcher 全是本地 fallback）。
-- 提升为字典表后：筛选变成外键连接而非中文字符串相等；餐厅可以改名或停用
-- 而不必回写所有历史帖子；后端终于能真的实现 /config 与管理端词表维护接口。
--
-- 词表由后端写死（种子见 00002），前端只做选择，不能自由填写。
-- 用户想要新词条走 dictionary_suggestions 提议流程（见文件末尾）。
-- ============================================================

CREATE TABLE canteens (
    id         bigint       PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    code       varchar(64)  NOT NULL,
    name       varchar(100) NOT NULL,
    campus     varchar(50)  NOT NULL,
    sort_order integer      NOT NULL DEFAULT 0,
    is_active  boolean      NOT NULL DEFAULT true,
    created_at timestamptz  NOT NULL DEFAULT now(),
    updated_at timestamptz  NOT NULL DEFAULT now()
);

ALTER TABLE canteens
    ADD CONSTRAINT canteens_code_trimmed_check CHECK (code = btrim(code) AND btrim(code) <> ''),
    ADD CONSTRAINT canteens_name_trimmed_check CHECK (name = btrim(name) AND btrim(name) <> ''),
    ADD CONSTRAINT canteens_campus_trimmed_check CHECK (campus = btrim(campus) AND btrim(campus) <> '');

CREATE UNIQUE INDEX uq_canteens_code ON canteens (code);
CREATE UNIQUE INDEX uq_canteens_name ON canteens (name);

COMMENT ON TABLE  canteens IS
  '餐厅/食堂字典。由 00002 迁移种子化，之后由管理端接口维护。'
  '一个帖子对应一个餐厅，餐厅下可以再细分窗口（canteen_windows）。';
COMMENT ON COLUMN canteens.code IS
  '对外稳定标识，/config 端点以此作为 CanteenConfig.id 返回（前端既有取值如 canteen-south）。名称可改，code 不可改。';
COMMENT ON COLUMN canteens.campus IS '所属校区，用于前端按校区分组，如「邯郸校区」「江湾校区」。';
COMMENT ON COLUMN canteens.is_active IS '停用后不再出现在 /config 选项中，但历史帖子的外键仍然有效。';

-- ------------------------------------------------------------
-- canteen_windows：餐厅下的窗口
--
-- 产品形态：帖子 → 餐厅（可空）→ 窗口（可空）。用户常常不知道具体窗口，
-- 所以窗口允许留空；但只要填了，就必须是所选餐厅名下的窗口。
-- 这条一致性由 posts 上的**复合外键**声明式保证，无需触发器或应用层校验：
--   FOREIGN KEY (canteen_window_id, canteen_id) → canteen_windows (id, canteen_id)
-- 外键默认 MATCH SIMPLE：任一列为 NULL 即跳过检查，恰好实现「窗口可空」。
--
-- 为未来的「某窗口下有哪些帖子」页面预留：posts.canteen_window_id 上有偏索引。
-- ------------------------------------------------------------

CREATE TABLE canteen_windows (
    id         bigint       PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    canteen_id bigint       NOT NULL REFERENCES canteens (id) ON DELETE CASCADE,
    name       varchar(100) NOT NULL,
    floor      varchar(20),
    sort_order integer      NOT NULL DEFAULT 0,
    is_active  boolean      NOT NULL DEFAULT true,
    created_at timestamptz  NOT NULL DEFAULT now(),
    updated_at timestamptz  NOT NULL DEFAULT now(),

    -- 只拒空白不够：' 1F' / '1F ' / '1F' 会被当成三个不同楼层，绕过唯一约束
    CONSTRAINT canteen_windows_name_trimmed_check
        CHECK (name = btrim(name) AND btrim(name) <> ''),
    CONSTRAINT canteen_windows_floor_trimmed_check
        CHECK (floor IS NULL OR (floor = btrim(floor) AND btrim(floor) <> '')),
    -- 同餐厅同楼层内窗口名唯一。NULLS NOT DISTINCT（PG15+）让「楼层未填」也参与判重，
    -- 否则两条都不填楼层的同名窗口会被放过。
    CONSTRAINT uq_canteen_windows_name UNIQUE NULLS NOT DISTINCT (canteen_id, floor, name),
    -- id 已是主键，此唯一约束逻辑上冗余，但 PostgreSQL 要求被复合外键引用的
    -- 列组必须存在唯一约束，posts 与 dictionary_suggestions 的复合外键依赖它。请勿删除。
    CONSTRAINT uq_canteen_windows_id_canteen UNIQUE (id, canteen_id)
);

CREATE INDEX idx_canteen_windows_canteen ON canteen_windows (canteen_id, sort_order);

COMMENT ON TABLE canteen_windows IS
  '餐厅窗口。种子为空，由管理端录入或经 dictionary_suggestions 审核后创建。';
COMMENT ON COLUMN canteen_windows.canteen_id IS
  '所属餐厅。餐厅被删除时窗口一并级联删除（但餐厅通常只停用不删除）。';
COMMENT ON COLUMN canteen_windows.floor IS
  '楼层，可空——很多窗口没有明确楼层，或用户填不出来。'
  '用 varchar 而非整数是为了容纳「B1」「负一层」「夹层」这类非数字写法。'
  '参与同餐厅内的窗口名判重（同名不同层视为两个窗口）。';

CREATE TABLE cuisines (
    id         bigint      PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    name       varchar(50) NOT NULL,
    sort_order integer     NOT NULL DEFAULT 0,
    is_active  boolean     NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE cuisines
    ADD CONSTRAINT cuisines_name_trimmed_check CHECK (name = btrim(name) AND btrim(name) <> '');

CREATE UNIQUE INDEX uq_cuisines_name ON cuisines (name);

COMMENT ON TABLE  cuisines IS '菜系字典，如「中式」「日式」。取值同时是 API 对外的字符串。';
COMMENT ON COLUMN cuisines.sort_order IS '/config 返回顺序，越小越靠前。';

CREATE TABLE flavors (
    id         bigint      PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    name       varchar(50) NOT NULL,
    sort_order integer     NOT NULL DEFAULT 0,
    is_active  boolean     NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE flavors
    ADD CONSTRAINT flavors_name_trimmed_check CHECK (name = btrim(name) AND btrim(name) <> '');

CREATE UNIQUE INDEX uq_flavors_name ON flavors (name);

COMMENT ON TABLE flavors IS
  '口味字典。种子取自前端既有词表，其中「川菜/湘菜/粤菜」其实是菜系、'
  '「微辣/中辣/特辣/麻辣/香辣」是同一维度的档位——分类学上不干净，'
  '但属产品口径问题，此处按现状种子化，重新划分需单独决策。';


-- ============================================================
-- tags：自由标签，用户可任意创建
--
-- 与上面几张字典表不同，tags 是开放集合：用户输入什么就有什么，不走审核。
-- 之所以也建表而不留 text[]，是为了支撑按标签检索、标签重命名与合并、
-- 以及热门标签统计（用 post_tags 上的 GROUP BY 现算，不做冗余计数列）。
--
-- 因为开放，所以必须限流：单个标签最长 10 字符，单帖最多 10 个标签
-- （后者是行数上限，在应用层校验）。
-- ============================================================

CREATE TABLE tags (
    id         bigint      PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    name       varchar(10) NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),

    -- 机审结论：标签是用户自由创建的，走「先发后审」
    moderation varchar(16) NOT NULL DEFAULT 'pending',
    deleted_at timestamptz,

    CONSTRAINT tags_name_not_blank_check CHECK (btrim(name) <> ''),
    -- varchar(10) 已限长；此约束额外排除「首尾空白凑长度」的绕过写法
    CONSTRAINT tags_name_trimmed_check   CHECK (name = btrim(name)),
    CONSTRAINT tags_moderation_check
        CHECK (moderation IN ('pending', 'pass', 'review', 'block'))
);

CREATE TRIGGER trg_tags_forbid_delete
    BEFORE DELETE ON tags
    FOR EACH ROW EXECUTE FUNCTION danshi_forbid_hard_delete();

-- 大小写不敏感唯一：中文无大小写，但英文标签 Spicy / spicy 应视为同一个。
-- 应用层负责写入前 trim + NFKC 归一化。
CREATE UNIQUE INDEX uq_tags_name_lower ON tags (lower(name));

COMMENT ON TABLE  tags IS
  '用户自由标签，无需审核。长度上限 10 字符由列类型与 CHECK 双重保证；'
  '单帖标签数上限（10 个）是行数约束，由应用层校验。';
COMMENT ON COLUMN tags.name IS '展示原文，保留用户输入的大小写；唯一性按 lower(name) 判定。';
COMMENT ON COLUMN tags.moderation IS
  '机审结论。标签走「先发后审」：创建即可用，机审异步跟进；'
  'block 时置 deleted_at 下架，该标签从所有帖子的展示中消失，但 post_tags 关联行保留以便误杀恢复。';
COMMENT ON COLUMN tags.deleted_at IS '非空表示已下架（违规或被合并）。物理删除被触发器拒绝。';


-- ============================================================
-- users
-- ============================================================

CREATE TABLE users (
    id              bigint       PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    email           varchar(255) NOT NULL,
    password_hash   varchar(255) NOT NULL,
    name            varchar(100) NOT NULL DEFAULT '',
    gender          varchar(10),
    bio             text,
    -- 头像外键在 image_assets 建表后追加（两表互相引用）
    avatar_image_asset_id bigint,
    role            varchar(20)  NOT NULL DEFAULT 'user',
    -- 封禁：取代旧库的布尔 is_active，支持限时与永久两种。
    -- 刻意**不用** timestamptz 的 'infinity' 表示永久：PostgreSQL 侧比较没问题，
    -- 但 pgx 用 pgtype.Timestamptz.InfinityModifier 单独表示无穷时间，
    -- GORM 模型若直接用 *time.Time 会扫描失败或序列化出意外结果。
    -- 用一个显式布尔换掉这个坑，代价只是多一列。
    --   未封禁：ban_is_permanent=false 且 banned_until IS NULL
    --   永久：  ban_is_permanent=true  且 banned_until IS NULL
    --   限时：  ban_is_permanent=false 且 banned_until=到期时刻（到期自动解封，无需定时任务）
    -- 判定是否处于封禁中：ban_is_permanent OR banned_until > now()
    ban_is_permanent boolean     NOT NULL DEFAULT false,
    banned_until    timestamptz,
    ban_reason      varchar(200),
    -- 可空：旧库的停用记录没有操作人，迁移时如实留空即可。
    -- 新产生的封禁由应用层负责填上，数据库不强制——
    -- 强制的代价是迁移只能随便挑个管理员顶上，那反而是往审计数据里写假信息。
    banned_by       bigint,
    -- 注销：软删除。硬删用户会经 author_id 级联抹掉其全部帖子与评论，
    -- 连带毁掉他人挂在其评论下的回复，与「删除不得伤及他人」直接冲突。
    deleted_at      timestamptz,
    created_at      timestamptz  NOT NULL DEFAULT now(),
    updated_at      timestamptz  NOT NULL DEFAULT now(),

    CONSTRAINT users_role_check   CHECK (role IN ('user', 'admin', 'super_admin')),
    CONSTRAINT users_gender_check CHECK (gender IS NULL OR gender IN ('male', 'female', 'other')),
    CONSTRAINT users_email_format_check CHECK (position('@' IN email) > 1),
    -- 永久与限时互斥：永久封禁不该再有到期时间
    CONSTRAINT users_ban_kind_check
        CHECK (NOT (ban_is_permanent AND banned_until IS NOT NULL)),
    -- 既然决定用布尔表达永久，就要把 infinity 这条后门也关上，
    -- 否则仍可写出 banned_until='infinity'，pgx/GORM 的无穷时间映射坑照样触发。
    CONSTRAINT users_ban_until_finite_check
        CHECK (banned_until IS NULL OR isfinite(banned_until)),
    -- 封禁要素成组。⚠ 必须显式写 ban_reason IS NOT NULL：
    -- btrim(NULL) <> '' 求值为 NULL，而 CHECK 只拒绝 FALSE 不拒绝 NULL，
    -- 少了这一句就能写出「封禁了但没有理由」。
    -- 封禁要素成组：封禁时理由必填，未封禁时理由与操作人都必须为空。
    -- ⚠ 必须显式写 ban_reason IS NOT NULL：btrim(NULL) <> '' 求值为 NULL，
    -- 而 CHECK 只拒绝 FALSE 不拒绝 NULL，少了这一句就能写出「封禁了但没有理由」。
    CONSTRAINT users_ban_fields_check CHECK (
        CASE WHEN ban_is_permanent OR banned_until IS NOT NULL
             THEN ban_reason IS NOT NULL AND btrim(ban_reason) <> ''
             ELSE ban_reason IS NULL AND banned_by IS NULL
        END
    )
);

-- 用 RESTRICT 而非 SET NULL：SET NULL 会在管理员账号被删时抹掉执行人，
-- 既丢失留痕，又直接违反上面「封禁时 banned_by 必须非空」的约束。
ALTER TABLE users
    ADD CONSTRAINT fk_users_banned_by FOREIGN KEY (banned_by) REFERENCES users (id) ON DELETE RESTRICT;

-- 后台「当前被封禁的用户」列表
CREATE INDEX idx_users_banned ON users (banned_until)
    WHERE ban_is_permanent OR banned_until IS NOT NULL;

-- 邮箱大小写不敏感唯一。旧库是区分大小写的 UNIQUE(email)，Foo@x 与 foo@x 可同时存在，属缺陷。
CREATE UNIQUE INDEX uq_users_email_lower ON users (lower(email));
CREATE INDEX idx_users_created_at ON users (created_at DESC);

COMMENT ON TABLE users IS
  '账号主体。封禁用 is_active，不物理删除——帖子、评论的外键都是 CASCADE，删用户会连带抹掉内容。';
COMMENT ON COLUMN users.email IS
  '注册时域名白名单由应用层 ALLOWED_EMAIL_DOMAINS 校验（fdueat.com / m.fudan.edu.cn / fudan.edu.cn）；登录不校验域名，存量非合规邮箱豁免。';
COMMENT ON COLUMN users.password_hash IS 'bcrypt，与 Python 侧二进制兼容，迁移后旧密码可直接登录。';
COMMENT ON COLUMN users.name IS '展示昵称，非唯一。空串表示未设置（非 NULL，简化前端处理）。';
COMMENT ON COLUMN users.gender IS
  '可空。前端 Gender 类型只产出 male / female，other 予以保留但前端不会提交。'
  '修改入口是 PUT 用户资料接口（update_user_profile），与 name / bio / 头像同一个接口。';
